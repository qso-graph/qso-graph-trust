"""Generate Cabrillo's ADIF values; verify the pinned upstream XML before use."""
import hashlib
import json
import subprocess
import sys
import xml.etree.ElementTree as ET
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'data/adif-318'
OUT = ROOT / 'crates/qso-graph-trust/src/cabrillo_tables.rs'
COMMENT = b'\n<!-- SPDX-License-Identifier: GPL-3.0-or-later -->\n'
HASHES = {
    'contest_id': 'b96700208505e0ca779518bc176a84f727ebb7a50227fac091ba828268113544',
    'band': 'a9df805c6ff594fcc99a4b908148ab0ed54f033dc978f50e24745ec95aad008f',
    'mode': '7b782b19a46f14ec5146529fd4b9e2ff8227591540ca8aab97f194ce56ca0cba',
}


def rows(name):
    raw = (DATA / f'enumerations_{name}.xml').read_bytes().replace(COMMENT, b'', 1)
    if hashlib.sha256(raw).hexdigest() != HASHES[name]:
        raise SystemExit(f'ADIF 3.1.8 {name}: source hash mismatch')
    top = ET.fromstring(raw)
    assert top.get('version') == '3.1.8'
    return [{v.get('name'): v.text or '' for v in r} for r in top.findall('.//record')]


def generate():
    overrides = {}
    for line in (DATA / 'exchanges.tsv').read_text().splitlines():
        if line and not line.startswith('#'):
            name, position, citation = line.split('\t')
            overrides[name] = (position, citation)
    out = ['// SPDX-License-Identifier: GPL-3.0-or-later',
           '// Generated by scripts/gen-cabrillo-tables.py; ADIF 3.1.8. Do not edit.',
           'use super::cabrillo::Contest;', 'pub(crate) const CONTESTS: &[Contest] = &[']
    contests = rows('contest_id')
    assert len(contests) == 260
    # These two sponsor identifiers are explicitly supported, but are absent from ADIF 3.1.8.
    sponsor_ids = {'WRTC', 'WRTC-2018'}
    for r in contests + [{'Contest-ID': name} for name in sorted(sponsor_ids)]:
        name = r['Contest-ID']
        position, citation = overrides.get(name, ('7', 'guessed'))
        positions = [int(value) for value in position.split('/')]
        assert len(positions) == 1 or (name == 'ARRL-160' and positions == [6, 7])
        short = f'Some({positions[0]})' if len(positions) == 2 else 'None'
        position = positions[-1]
        out.append(f'    Contest {{ id: {json.dumps(name)}, call: {position}, short_call: {short}, source: {json.dumps(citation)} }},')
    assert overrides.keys() <= {r['Contest-ID'] for r in contests} | sponsor_ids
    assert all(overrides[name][1].startswith('https://') for name in sponsor_ids)
    out += ['];', 'pub(crate) const BANDS: &[(&str, u64, u64)] = &[']
    for r in rows('band'):
        lo, hi = [int(Decimal(r[k]) * 1000000) for k in ('Lower Freq (MHz)', 'Upper Freq (MHz)')]
        out.append(f'    ({json.dumps(r["Band"])}, {lo}, {hi}),')
    out += ['];', 'pub(crate) const MODES: &[&str] = &[']
    out += [f'    {json.dumps(r["Mode"])},' for r in rows('mode')]
    out += ['];', '']
    result = subprocess.run(['rustfmt', '--edition', '2024', '--emit', 'stdout'], input='\n'.join(out), text=True, check=True, capture_output=True)
    return result.stdout


if __name__ == '__main__':
    result = generate()
    if '--check' in sys.argv:
        if OUT.read_text() != result:
            raise SystemExit('Cabrillo tables are stale')
        print('Cabrillo tables and ADIF 3.1.8 hashes match')
    else:
        OUT.write_text(result)
        print(f'Generated Cabrillo tables: {len(rows("contest_id"))} ADIF contests and 2 sponsor identifiers')
