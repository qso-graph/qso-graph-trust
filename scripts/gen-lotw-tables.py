"""Writes crates/qso-graph-trust/src/lotw/tables.rs from ARRL's TQSL configuration, data/tqsl-config/config.xml.

The configuration is the data LoTW checks a signed log against: its bands, modes, ADIF mode map,
propagation modes, satellites, DXCC entities, station-location fields and pages, and the signature
specification. QG Trust reads it as data, never TQSL's code. The tables are generated, not parsed at
run time, so the library carries no XML parser.

    scripts/gen-lotw-tables.py           write the tables
    scripts/gen-lotw-tables.py --check   fail if the tables, or the crate's copy of ARRL's terms, are not what
                                         data/tqsl-config gives (CI)

A developer tool only, never shipped; standard library only.
"""

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "data/tqsl-config/config.xml"
OUT = ROOT / "crates/qso-graph-trust/src/lotw/tables.rs"
# ARRL's terms, copied into the crate so the published package carries them (their clause 1).
LICENSE = ROOT / "data/tqsl-config/LICENSE.txt"
LICENSE_COPY = ROOT / "crates/qso-graph-trust/LICENSE-ARRL.md"
SIGSPEC = ("LOTW", "2.0")


def rs(s):
    """A Rust string literal."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def opt(s):
    return f"Some({rs(s)})" if s else "None"


def generate():
    top = ET.parse(CONFIG).getroot()
    major, minor = top.get("majorversion"), top.get("minorversion")
    out = []
    w = out.append
    w("// Generated by scripts/gen-lotw-tables.py from data/tqsl-config/config.xml: do not edit.")
    w("// Regenerate with the script; CI runs it with --check.")
    w("//")
    w("// The data is ARRL's TQSL configuration, Copyright (C) 2001-2015 American Radio Relay League, Inc.,")
    w("// portions (C) 2003-2026 The TrustedQSL Developers, redistributed under ARRL's terms in")
    w("// LICENSE-ARRL.md at this crate's root, whose notice and disclaimer this file carries by reference.")
    w("")
    w("use super::{AdifMode, Band, DxccEntity, FieldKind, LocField, LocPage, Spectrum};")
    w("")
    w(f"/// The configuration's version, as config.xml states it.")
    w(f"pub const CONFIG_VERSION: (u32, u32) = ({int(major)}, {int(minor)});")
    w("")

    w("pub const BANDS: &[Band] = &[")
    for b in top.find("bands"):
        sp = {"HF": "Hf", "VHF": "Vhf", "UHF": "Uhf"}[b.get("spectrum")]
        w(f"    Band {{ name: {rs(b.text.strip())}, spectrum: Spectrum::{sp}, low: {int(b.get('low'))}, high: {int(b.get('high'))} }},")
    w("];")
    w("")

    w("pub const MODES: &[&str] = &[")
    for m in top.find("modes"):
        w(f"    {rs(m.text.strip())},")
    w("];")
    w("")

    w("pub const ADIF_MODES: &[AdifMode] = &[")
    for m in top.find("adifmap"):
        w(f"    AdifMode {{ mode: {rs(m.get('adif-mode') or m.text.strip())}, submode: {opt(m.get('adif-submode'))}, lotw: {rs(m.get('mode') or m.text.strip())} }},")
    w("];")
    w("")

    w("pub const PROP_MODES: &[&str] = &[")
    for p in top.find("propmodes"):
        w(f"    {rs(p.get('name'))},")
    w("];")
    w("")

    w("pub const SATELLITES: &[&str] = &[")
    for s in top.find("satellites"):
        w(f"    {rs(s.get('name'))},")
    w("];")
    w("")

    w("pub const DXCC: &[DxccEntity] = &[")
    for e in top.find("dxcc"):
        w(f"    DxccEntity {{ id: {int(e.get('arrlId'))}, name: {rs(e.text.strip())}, deleted: {'true' if e.get('deleted') == '1' else 'false'}, zones: {rs(e.get('zonemap') or '')} }},")
    w("];")
    w("")

    w("pub const LOC_FIELDS: &[LocField] = &[")
    enums = []
    for f in top.find("locfields"):
        kind = {"C": "Text", "I": "Int"}[f.get("type")]
        lower, upper = f.get("lower"), f.get("upper")
        rng = f"Some(({int(lower)}, {int(upper)}))" if lower is not None else "None"
        w(f"    LocField {{ id: {rs(f.get('Id'))}, kind: FieldKind::{kind}, len: {int(f.get('len'))}, range: {rng}, depends_on: {opt(f.get('dependsOn'))}, shown: {'false' if f.get('intype') == '4' else 'true'} }},")
        for group in f.findall("enums"):
            for e in group.findall("enum"):
                enums.append((f.get("Id"), group.get("dependency") or "", e.get("value"), e.get("zonemap") or ""))
    w("];")
    w("")
    w("/// Each list field's values: (field, the value of the field it depends on or \"\", value,")
    w("/// the ITU:CQ zone pairs it lies in or \"\").")
    w("pub const LOC_ENUMS: &[(&str, &str, &str, &str)] = &[")
    for f, d, v, z in enums:
        w(f"    ({rs(f)}, {rs(d)}, {rs(v)}, {rs(z)}),")
    w("];")
    w("")

    w("/// List labels that differ from their stored values: (field, dependency, value, label).")
    w("pub const LOC_LABELS: &[(&str, &str, &str, &str)] = &[")
    for f in top.find("locfields"):
        for group in f.findall("enums"):
            for e in group.findall("enum"):
                label = (e.text or "").strip()
                if label and label.upper() != e.get("value").upper():
                    w(f"    ({rs(f.get('Id'))}, {rs(group.get('dependency') or '')}, {rs(e.get('value'))}, {rs(label)}),")
    w("];")
    w("")

    w("pub const LOC_PAGES: &[LocPage] = &[")
    for p in top.find("locpages"):
        fields = ", ".join(rs(x.text.strip()) for x in p.findall("pageField"))
        dep = p.get("dependency")
        dxcc = f"Some({int(dep)})" if dep else "None"
        w(f"    LocPage {{ id: {int(p.get('Id'))}, follows: {int(p.get('follows'))}, dxcc: {dxcc}, fields: &[{fields}] }},")
    w("];")
    w("")

    spec = next(s for s in top.find("sigspecs")
                if (s.get("name"), s.get("version")) == SIGSPEC)
    w(f"/// The signature's field name, from the {SIGSPEC[0]} {SIGSPEC[1]} signature specification.")
    w(f"pub const SIGNATURE_FIELD: &str = {rs('SIGN_' + SIGSPEC[0] + '_V' + SIGSPEC[1])};")
    w("/// The signed QSO fields, in order, and whether each is required.")
    w("pub const SIGN_CONTACT: &[(&str, bool)] = &[")
    for f in spec.find("tCONTACT"):
        w(f"    ({rs(f.tag)}, {'true' if f.get('required') == '1' else 'false'}),")
    w("];")
    w("/// The signed station fields, in order.")
    w("pub const SIGN_STATION: &[&str] = &[")
    for f in spec.find("tSTATION"):
        w(f"    {rs(f.tag)},")
    w("];")
    return "\n".join(out) + "\n"


def main():
    text = generate()
    if sys.argv[1:] == ["--check"]:
        if OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is not what config.xml gives: run scripts/gen-lotw-tables.py")
        if not LICENSE_COPY.is_file() or LICENSE_COPY.read_bytes() != LICENSE.read_bytes():
            sys.exit(f"{LICENSE_COPY.relative_to(ROOT)} is not ARRL's terms as {LICENSE.relative_to(ROOT)} has them: run scripts/gen-lotw-tables.py")
        return
    if sys.argv[1:]:
        sys.exit(__doc__)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    LICENSE_COPY.write_bytes(LICENSE.read_bytes())


if __name__ == "__main__":
    main()
